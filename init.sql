CREATE TABLE `shop_plugins` (
  `plugin_id` varchar(255) NOT NULL,
  `name` varchar(255) NOT NULL,
  `description` text DEFAULT NULL,
  `version` varchar(50) NOT NULL,
  `author` varchar(255) NOT NULL,
  `source` enum('unknown','mone-registry','github','local') NOT NULL DEFAULT 'unknown',
  `enabled` text NOT NULL,
  `install_path` text DEFAULT NULL,
  `checksum` varchar(255) DEFAULT NULL,
  `repository_url` text DEFAULT NULL,
  `required_momentushop_version` varchar(50) DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`plugin_id`) /*T![clustered_index] CLUSTERED */,
  KEY `idx_shop_plugins_name` (`name`),
  KEY `idx_shop_plugins_author` (`author`),
  KEY `idx_shop_plugins_repository_url` (`repository_url`(255))
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_bin

CREATE TABLE `shop_commands` (
  `command_id` varchar(255) NOT NULL,
  `plugin_id` varchar(255) NOT NULL,
  `name` varchar(255) NOT NULL,
  `description` text NOT NULL,
  `enabled` text NOT NULL,
  `type` varchar(50) NOT NULL,
  `aliases` json DEFAULT NULL,
  `owner_only` text NOT NULL,
  `developer_only` text NOT NULL,
  `premium_only` text NOT NULL,
  `guild_only` text NOT NULL,
  `nsfw` text NOT NULL,
  `status` varchar(50) NOT NULL,
  `cooldown` int NOT NULL DEFAULT '0',
  `checksum` varchar(255) DEFAULT NULL,
  `registered_by` varchar(255) DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`command_id`) /*T![clustered_index] CLUSTERED */,
  KEY `idx_shop_commands_plugin_id` (`plugin_id`),
  KEY `idx_shop_commands_name` (`name`),
  KEY `idx_shop_commands_type` (`type`),
  CONSTRAINT `fk_shop_commands_plugin` FOREIGN KEY (`plugin_id`) REFERENCES `shop_plugins` (`plugin_id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_bin